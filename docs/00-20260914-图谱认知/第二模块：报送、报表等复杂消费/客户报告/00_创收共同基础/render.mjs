// Documentation assembly only. Reuses the existing 107491 include expander.
// No macro substitution, database connection, or SQL execution.
import {readFileSync, writeFileSync, realpathSync, lstatSync, existsSync} from 'node:fs';
import {dirname, resolve, relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {expand} from '../../公共加工/03_逐日本金与费用/render.mjs';

export const root = dirname(fileURLToPath(import.meta.url));
export const branches = Object.freeze(['01_期权_230202', '02_普通互换_230204', '03_金仕达_223867']);
export const header = '-- GENERATED by ../render.mjs; edit the branch main SQL and its includes.\n';

function branchDirectory(branch) {
  if (!branches.includes(branch)) throw new Error('Unknown revenue branch: ' + branch);
  return resolve(root, branch);
}

function realBranchDirectory(branch) {
  const actual = realpathSync(branchDirectory(branch));
  if (relative(realpathSync(root), actual) !== branch) {
    throw new Error('Revenue branch resolves outside its documented directory');
  }
  return actual;
}

export function expandBranch(branch, readOverride) {
  branchDirectory(branch);
  const read = readOverride ?? (name => {
    const base = realBranchDirectory(branch);
    const file = realpathSync(resolve(base, name));
    if (dirname(file) !== base) throw new Error('SQL include resolves outside branch');
    return readFileSync(file, 'utf8');
  });
  return expand('00_主脚本.sql', read);
}

export const render = (branch, readOverride) => header + expandBranch(branch, readOverride);

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [branch, mode] = process.argv.slice(2);
    if (process.argv.length !== 4 || !['--write', '--print'].includes(mode)) {
      throw new Error('Usage: node render.mjs <documented-branch> --write | --print');
    }
    const sql = render(branch);
    if (mode === '--print') process.stdout.write(sql);
    else {
      const target = resolve(realBranchDirectory(branch), '完整SQL.sql');
      try {
        if (lstatSync(target).isSymbolicLink()) throw new Error('Refusing symlink output');
      } catch (error) {
        if (error.code !== 'ENOENT') throw error;
      }
      if (existsSync(target) && !readFileSync(target, 'utf8').startsWith(header)) {
        throw new Error('Refusing to replace a non-generated SQL file');
      }
      writeFileSync(target, sql, 'utf8');
      console.log('Expanded ' + branch + '; no SQL executed.');
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
