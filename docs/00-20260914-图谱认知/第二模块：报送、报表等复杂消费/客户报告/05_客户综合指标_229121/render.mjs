// Documentation-only include expansion; no macro substitution or SQL execution.
import {readFileSync,writeFileSync,realpathSync,lstatSync,existsSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {expand} from '../../公共加工/03_逐日本金与费用/render.mjs';
export const root=dirname(fileURLToPath(import.meta.url));
export const header='-- GENERATED by render.mjs; edit 00_主脚本.sql and its includes.\n';
export const render=(readOverride)=>header+expand('00_主脚本.sql',readOverride??(name=>{
  const base=realpathSync(root),file=realpathSync(resolve(base,name));
  if(dirname(file)!==base)throw Error('SQL include resolves outside this report');
  return readFileSync(file,'utf8');
}));
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    const mode=process.argv[2];
    if(process.argv.length!==3||!['--write','--print'].includes(mode))throw Error('Usage: node render.mjs --write | --print');
    const sql=render();
    if(mode==='--print')process.stdout.write(sql);
    else{
      const target=resolve(realpathSync(root),'完整SQL.sql');
      try{if(lstatSync(target).isSymbolicLink())throw Error('Refusing symlink output');}catch(e){if(e.code!=='ENOENT')throw e;}
      if(existsSync(target)&&!readFileSync(target,'utf8').startsWith(header))throw Error('Refusing non-generated output');
      writeFileSync(target,sql,'utf8');
      console.log('Expanded 229121; no SQL executed.');
    }
  }catch(e){console.error(e.message);process.exitCode=1;}
}
