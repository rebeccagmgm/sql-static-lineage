import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = dirname(fileURLToPath(import.meta.url));
export const header = '-- GENERATED by render.mjs; edit 00_主脚本.sql and numbered modules instead.\n';
export function expand(name = '00_主脚本.sql', read = n => readFileSync(join(root, n), 'utf8'), active = []) {
  if (!/^[^/\\:]+\.sql$/.test(name) || name.includes('..')) throw Error('Only flat SQL paths are allowed');
  if (active.includes(name)) throw Error('Circular SQL include: ' + name);
  const source = read(name);
  if (typeof source !== 'string' || !source.trim()) throw Error('Missing or empty SQL: ' + name);
  return source.replace(/^[ \t]*-- @include ([^\r\n]+)\r?$/gm,
    (_, child) => expand(child.trim(), read, [...active, name]));
}
export const render = () => header + expand();

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (!['--write', '--print'].includes(mode) || process.argv.length !== 3) {
    throw Error('Usage: node render.mjs --write|--print');
  }
  const result = render();
  if (mode === '--print') process.stdout.write(result);
  else {
    const output = join(root, '完整SQL.sql');
    if (existsSync(output) && !readFileSync(output, 'utf8').startsWith(header)) {
      throw Error('Refusing to overwrite a non-generated file');
    }
    writeFileSync(output, result, 'utf8');
    console.log('已展开：完整SQL.sql（不执行SQL，不替换日期变量）');
  }
}
