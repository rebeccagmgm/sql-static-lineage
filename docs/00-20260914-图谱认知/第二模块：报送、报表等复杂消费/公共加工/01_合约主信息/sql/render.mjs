import { readFileSync, realpathSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve, relative, isAbsolute, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(readFileSync(join(root, 'manifest.json'), 'utf8'));
const header = '-- GENERATED by render.mjs; edit manifest.json entries and 04_业务模块/ instead.\n';
const legacyHeader = '-- GENERATED by render.mjs; edit 03_分支主脚本/ and 04_业务模块/ instead.\n';

function withinRoot(path) {
  const rel = relative(root, path);
  if (rel === '..' || rel.startsWith('..' + '/') || rel.startsWith('..' + '\\') || isAbsolute(rel)) {
    throw new Error('Include path must stay within sql/');
  }
}

/** Expand SQL includes only; never substitute scheduler parameters or execute SQL. */
export function expand(entry, read = path => {
  withinRoot(realpathSync(path));
  return readFileSync(path, 'utf8');
}, active = []) {
  const path = resolve(root, entry);
  withinRoot(path);
  if (!path.endsWith('.sql')) throw new Error('Only .sql includes are allowed');
  if (active.includes(path)) throw new Error('Circular SQL include');
  const source = read(path);
  if (typeof source !== 'string') throw new Error('Missing SQL include: ' + relative(root, path));
  if (!source.trim()) throw new Error('Empty SQL include: ' + relative(root, path));
  return source.replace(/^[ \t]*-- @include ([^\r\n]+)\r?$/gm, (_, name) => {
    const next = resolve(dirname(path), name.trim());
    return expand(next, read, [...active, path]);
  });
}

export function render(branch) {
  const item = manifest.branches.find(b => b.name === branch);
  if (!item) throw new Error('Unknown branch: ' + branch);
  return header + expand(item.entry);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if ((args.length === 1 || args.length === 2) && args[0] === '--write') {
      const selected = args[1] ? manifest.branches.filter(b => b.name === args[1]) : manifest.branches;
      if (!selected.length) throw new Error('Unknown branch: ' + args[1]);
      // Render the selected inputs before writing; a broken include must not truncate output.
      const rendered = selected.map(b => ({ ...b, sql: render(b.name) }));
      const output = join(root, '05_完整SQL');
      mkdirSync(output, { recursive: true });
      withinRoot(realpathSync(output));
      for (const b of rendered) {
        const dest = join(output, b.name + '.sql');
        if (existsSync(dest)) {
          withinRoot(realpathSync(dest));
          const current = readFileSync(dest, 'utf8');
          if (!current.startsWith(header) && !current.startsWith(legacyHeader)) {
            throw new Error('Refusing to overwrite a file not generated by render.mjs: ' + b.name);
          }
        }
        writeFileSync(dest, b.sql, 'utf8');
      }
      console.log('Expanded ' + selected.length + ' branches into sql/05_完整SQL; no SQL executed.');
    } else if (args.length === 1) {
      process.stdout.write(render(args[0]));
    } else {
      throw new Error('Usage: node render.mjs <branch> OR --write [branch]');
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
