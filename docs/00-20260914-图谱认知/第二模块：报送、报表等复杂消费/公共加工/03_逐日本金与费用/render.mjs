// Local documentation helper: expands includes, never substitutes dates or executes SQL.
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export const root = dirname(fileURLToPath(import.meta.url));
export const header = '-- GENERATED by render.mjs; edit 00_主脚本.sql and 01–06 modules instead.\n';
export function expand(name = '00_主脚本.sql', read = n => readFileSync(join(root,n),'utf8'), active = []) {
  if (!/^[^/\\:]+\.sql$/.test(name) || name.includes('..')) throw new Error('Only flat SQL paths are allowed');
  if (active.includes(name)) throw new Error('Circular SQL include: ' + name);
  const source = read(name);
  if (typeof source !== 'string' || !source.trim()) throw new Error('Missing or empty SQL: ' + name);
  return source.replace(/^[ \t]*-- @include ([^\r\n]+)\r?$/gm,
    (_, child) => expand(child.trim(),read,[...active,name]));
}
export const render = () => header + expand();
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 3 || !['--write','--print'].includes(process.argv[2])) {
      throw new Error('Usage: node render.mjs --write | --print');
    }
    const sql = render();
    if (process.argv[2] === '--print') process.stdout.write(sql);
    else {
      const output = join(root,'完整SQL.sql');
      if (existsSync(output) && !readFileSync(output,'utf8').startsWith(header)) {
        throw new Error('Refusing to replace a file not generated by this helper');
      }
      writeFileSync(output,sql,'utf8');
      console.log('Expanded 107491 into 完整SQL.sql; no SQL executed.');
    }
  } catch (error) { console.error(error.message); process.exitCode=1; }
}
