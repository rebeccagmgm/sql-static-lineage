// Documentation assembly only: no SQL execution or parameter substitution.
import {readFileSync, writeFileSync, realpathSync, lstatSync, existsSync} from 'node:fs';
import {dirname, resolve, relative, extname} from 'node:path';
import {fileURLToPath} from 'node:url';

export const root = dirname(fileURLToPath(import.meta.url));
export const header = '-- GENERATED by render.mjs; edit 00–06 SQL modules.\n';
function permitted(path) {
  const local = relative(root, path);
  return extname(path) === '.sql' && local !== '' &&
    !local.startsWith('..') && !local.includes('/') && !local.includes('\\');
}
function readDefault(path) {
  if (!permitted(realpathSync(path))) throw Error('SQL include resolves outside local directory');
  return readFileSync(path, 'utf8');
}
export function expand(name = '00_主脚本.sql', read = readDefault, active = []) {
  const path = resolve(root, name);
  if (!permitted(path)) throw Error('SQL include outside local directory: ' + name);
  if (active.includes(path)) throw Error('Circular SQL include: ' + name);
  const source = read(path);
  if (typeof source !== 'string' || !source.trim()) throw Error('Missing or empty SQL: ' + name);
  return source.replace(/^[ \t]*-- @include ([^\r\n]+)\r?$/gm,
    (_, child) => expand(child.trim(), read, [...active, path]));
}
export const render = () => header + expand();
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 3 || !['--write', '--print'].includes(process.argv[2]))
      throw Error('Usage: node render.mjs --write | --print');
    const sql = render();
    if (process.argv[2] === '--print') process.stdout.write(sql);
    else {
      const target = resolve(root, '完整SQL.sql');
      let stat;
      try { stat = lstatSync(target); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (stat?.isSymbolicLink()) throw Error('Refusing to replace symlink output');
      if (existsSync(target) && !readFileSync(target, 'utf8').startsWith(header))
        throw Error('Refusing to replace non-generated 完整SQL.sql');
      writeFileSync(target, sql, 'utf8');
      console.log('Expanded 114013 into 完整SQL.sql; no SQL executed.');
    }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
