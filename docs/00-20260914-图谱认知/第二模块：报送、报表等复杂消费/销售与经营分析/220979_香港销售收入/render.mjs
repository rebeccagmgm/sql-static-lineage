// Documentation-only assembly: no variable substitution and no SQL execution.
import {readFileSync,writeFileSync,existsSync,realpathSync,lstatSync} from 'node:fs';
import {dirname,resolve,relative,extname} from 'node:path';
import {fileURLToPath} from 'node:url';
export const root=dirname(fileURLToPath(import.meta.url));
const outside=[];
export const header='-- GENERATED by render.mjs; edit the numbered SQL modules.\n';
function permitted(path){
  const local=relative(root,path);
  return extname(path)==='.sql'&&
    ((!local.includes('/')&&!local.includes('\\')&&local!==''&&!local.startsWith('..'))||outside.includes(path));
}
const readDefault=path=>{
  // A symlink cannot turn an allowed include name into a read outside the permitted SQL set.
  if(!permitted(realpathSync(path)))throw Error('SQL include resolves outside allowed paths: '+path);
  return readFileSync(path,'utf8');
};
export function expand(name='00_主脚本.sql',read=readDefault,active=[],parent=root){
  const path=resolve(parent,name);
  if(!permitted(path))throw Error('SQL include outside allowed paths: '+name);
  if(active.includes(path))throw Error('Circular SQL include: '+name);
  const source=read(path);
  if(typeof source!=='string'||!source.trim())throw Error('Missing or empty SQL: '+name);
  return source.replace(/^[ \t]*-- @include ([^\r\n]+)\r?$/gm,
    (_,child)=>expand(child.trim(),read,[...active,path],dirname(path)));
}
export const render=()=>header+expand();
export function assertOutputNotSymlink(target){
  let stat;
  try{stat=lstatSync(target);}catch(error){if(error.code==='ENOENT')return;throw error;}
  if(stat.isSymbolicLink())throw Error('Refusing to write symlink output: '+target);
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    if(process.argv.length!==3||!['--write','--print'].includes(process.argv[2]))
      throw Error('Usage: node render.mjs --write | --print');
    const sql=render();
    if(process.argv[2]==='--print')process.stdout.write(sql);
    else{
      const target=resolve(root,'完整SQL.sql');
      assertOutputNotSymlink(target);
      if(existsSync(target)&&!readFileSync(target,'utf8').startsWith(header))
        throw Error('Refusing to replace non-generated 完整SQL.sql');
      writeFileSync(target,sql,'utf8');
      console.log('Expanded 220979 into 完整SQL.sql; no SQL executed.');
    }
  }catch(error){console.error(error.message);process.exitCode=1;}
}
